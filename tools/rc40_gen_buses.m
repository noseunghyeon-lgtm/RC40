function outFile = rc40_gen_buses(hwPins, cfg)
%RC40_GEN_BUSES  Write an .m script that defines Simulink.Bus objects and
%                matching parameter structs for the HW output ports.
%
%   outFile = RC40_GEN_BUSES(hwPins, cfg)
%
%   Only Use=ON HwOutp pins are included. Grouping:
%     RelU / AbsltU (voltage outputs)  -> cfg.busNames.V   (default 'VO')
%     High side outputs (HS_...)       -> cfg.busNames.HS  (default 'DOHS')
%     Low side outputs  (LS_...)       -> cfg.busNames.LS  (default 'DOLS')
%   Element name = port name, element type = port data type (uint16, boolean ...),
%   dimensions 1, fixed, real. For each bus <name> a struct <name>_Param is
%   created with the same field names and zero values of the element type.
%   Order inside a bus follows the Pinmap order.

    outFile = '';
    if isempty(hwPins), return; end
    outP = hwPins(strcmp({hwPins.dir}, 'Out') & logical([hwPins.used]));
    if isempty(outP), return; end

    keys = {'HS','LS','V'};
    grp  = cell(1, numel(outP));
    for i = 1:numel(outP)
        hp = outP(i);
        if any(strcmp(hp.hwArray, {'RelU','AbsltU'}))
            grp{i} = 'V';
        elseif any(strcmp(hp.side, {'HS','LS'}))
            grp{i} = hp.side;
        else
            grp{i} = '';
            warning('rc40:BusNoSide', ...
                '%s (%s): no High/Low side in Description, not placed in any bus', hp.pin, hp.portName);
        end
    end

    outFile = cfg.busOutFile;
    d = fileparts(outFile);
    if ~isempty(d) && exist(d,'dir') ~= 7, mkdir(d); end
    fid = fopen(outFile, 'w');
    if fid < 0, warning('rc40:BusWrite','Cannot write %s', outFile); outFile = ''; return; end
    c = onCleanup(@() fclose(fid));

    fprintf(fid, '%% Auto-generated by rc40_gen_buses from RC40_Pinmap.xlsx (Use = ON HwOutp pins).\n');
    fprintf(fid, '%% Creates Simulink.Bus objects and <bus>_Param structs in the base workspace.\n');
    fprintf(fid, '%% Groups: HS outputs, LS outputs, voltage outputs (RelU/AbsltU).\n\n');

    nBus = 0;
    for k = 1:numel(keys)
        sel = find(strcmp(grp, keys{k}));
        if isempty(sel), continue; end
        bus = cfg.busNames.(keys{k});
        nBus = nBus + 1;
        fprintf(fid, '%%%% %s\n', bus);
        fprintf(fid, 'clear elems;\n');
        for j = 1:numel(sel)
            hp = outP(sel(j));
            fprintf(fid, 'elems(%d) = Simulink.BusElement;\n', j);
            fprintf(fid, 'elems(%d).Name = ''%s'';\n', j, hp.portName);
            fprintf(fid, 'elems(%d).Dimensions = 1;\n', j);
            fprintf(fid, 'elems(%d).DimensionsMode = ''Fixed'';\n', j);
            fprintf(fid, 'elems(%d).DataType = ''%s'';\n', j, hp.dataType);
            fprintf(fid, 'elems(%d).Complexity = ''real'';\n', j);
            fprintf(fid, 'elems(%d).SampleTime = -1;\n', j);
            fprintf(fid, 'elems(%d).Description = ''Pin %s'';\n', j, hp.pin);
        end
        fprintf(fid, '%s = Simulink.Bus;\n', bus);
        fprintf(fid, '%s.Elements = elems;\n', bus);
        fprintf(fid, 'clear elems;\n\n');

        fprintf(fid, '%s_Param = struct();\n', bus);
        for j = 1:numel(sel)
            hp = outP(sel(j));
            fprintf(fid, '%s_Param.%s = %s;\n', bus, hp.portName, rc40_zero_literal(hp.dataType));
        end
        fprintf(fid, '\n');
    end
    fprintf('Bus script written: %s  (%d buses, %d signals)\n', outFile, nBus, numel(outP));
end

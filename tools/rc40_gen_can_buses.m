function outFile = rc40_gen_can_buses(canBus, cfg)
%RC40_GEN_CAN_BUSES  Write an .m script that defines one Simulink.Bus and one
%                    parameter struct per CAN message.
%
%   outFile = RC40_GEN_CAN_BUSES(canBus, cfg)
%
%   canBus is the list of CAN ports the model generated (both Rx and Tx):
%     .message  CAN message name        .id        CAN ID
%     .dir      'In' | 'Out'            .name      port name (with type suffix)
%     .dataType Simulink data type      .sig       original signal name
%
%   For message <Msg> the script creates
%     <Msg>         Simulink.Bus, one element per signal (same order as the
%                   generated ports), element type = port data type
%     <Msg>_Param   struct with the same field names, typed zero values
%   Element names follow the port names (cfg.canBusElementName = 'port', the
%   default) or the plain DBC/Excel signal names ('signal').

    outFile = '';
    if isempty(canBus), return; end

    useSig = strcmpi(getOpt(cfg, 'canBusElementName', 'port'), 'signal');
    [msgs, ~, msgIdx] = unique({canBus.message}, 'stable');   % first-seen order

    outFile = cfg.canBusOutFile;
    d = fileparts(outFile);
    if ~isempty(d) && exist(d,'dir') ~= 7, mkdir(d); end
    fid = fopen(outFile, 'w');
    if fid < 0, warning('rc40:CanBusWrite','Cannot write %s', outFile); outFile = ''; return; end
    c = onCleanup(@() fclose(fid));

    fprintf(fid, '%% Auto-generated by rc40_gen_can_buses (CAN messages of the MASAR CAN Excel).\n');
    fprintf(fid, '%% Creates one Simulink.Bus <Message> and one struct <Message>_Param per message\n');
    fprintf(fid, '%% in the base workspace.\n\n');

    maxLen = namelengthmax;
    for m = 1:numel(msgs)
        sel = find(msgIdx == m);
        bus = busVarName(msgs{m});
        if numel(bus) + numel('_Param') > maxLen
            warning('rc40:CanBusName', '%s: bus/param variable name exceeds %d characters', bus, maxLen);
        end
        first = canBus(sel(1));
        fprintf(fid, '%%%% %s  (MsgID=0x%X, %s)\n', bus, first.id, dirText(first.dir));
        fprintf(fid, 'clear elems;\n');
        names = cell(1, numel(sel));
        for j = 1:numel(sel)
            e = canBus(sel(j));
            if useSig, nm = e.sig; else, nm = e.name; end
            names{j} = nm;
            fprintf(fid, 'elems(%d) = Simulink.BusElement;\n', j);
            fprintf(fid, 'elems(%d).Name = ''%s'';\n', j, nm);
            fprintf(fid, 'elems(%d).Dimensions = 1;\n', j);
            fprintf(fid, 'elems(%d).DimensionsMode = ''Fixed'';\n', j);
            fprintf(fid, 'elems(%d).DataType = ''%s'';\n', j, e.dataType);
            fprintf(fid, 'elems(%d).Complexity = ''real'';\n', j);
            fprintf(fid, 'elems(%d).SampleTime = -1;\n', j);
            fprintf(fid, 'elems(%d).Description = ''Signal %s'';\n', j, e.sig);
        end
        fprintf(fid, '%s = Simulink.Bus;\n', bus);
        fprintf(fid, '%s.Elements = elems;\n', bus);
        fprintf(fid, '%s.Description = ''MsgID=0x%X | %s | Signals=%d'';\n', bus, first.id, dirText(first.dir), numel(sel));
        fprintf(fid, 'clear elems;\n\n');

        fprintf(fid, '%s_Param = struct();\n', bus);
        for j = 1:numel(sel)
            fprintf(fid, '%s_Param.%s = %s;\n', bus, names{j}, rc40_zero_literal(canBus(sel(j)).dataType));
        end
        fprintf(fid, '\n');
    end
    fprintf('CAN bus script written: %s  (%d buses, %d signals)\n', outFile, numel(msgs), numel(canBus));
end

function v = busVarName(msg)
%BUSVARNAME  Message name as a valid MATLAB identifier.
    v = regexprep(strtrim(msg), '[^\w]', '_');
    if isempty(v), v = 'Msg'; end
    if ~isempty(regexp(v, '^\d', 'once')), v = ['Msg_' v]; end
end

function t = dirText(dir)
    if strcmp(dir, 'Out'), t = 'Tx'; else, t = 'Rx'; end
end

function v = getOpt(s, f, def)
    if isfield(s, f), v = s.(f); else, v = def; end
end
